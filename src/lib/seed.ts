type RawItem = [id: string, name: string, rupees: number, prepSeconds?: number]

function buildItems(categoryId: string, rows: RawItem[]): MenuItem[] {
  return rows.map(([id, name, rupees, prep = 300], index) => ({
    id,
    category_id: categoryId,
    name,
    description: '',
    price_cents: rupees * 100,
    // Seed times were optimistic; scale for realistic kitchen wait.
    prep_time_seconds: Math.round(prep * 3),
    is_available: true,
    image_url: null,
    display_order: index + 1,
  }))
}

